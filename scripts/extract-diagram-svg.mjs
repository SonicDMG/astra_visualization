// Match <svg ... </svg>
const svgMatch = html.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/i);
if (!svgMatch) {
  console.error('Could not find <svg> tag in sorting-flow.html');
  process.exit(1);
}

let svgInner = svgMatch[1];

// Strip HTML comments
svgInner = svgInner.replace(/<!--[\s\S]*?-->/g, '');

// Strip <title> and <desc> if present since we declare them explicitly
svgInner = svgInner.replace(/<title\b[^>]*>[\s\S]*?<\/title>/gi, '');
svgInner = svgInner.replace(/<desc\b[^>]*>[\s\S]*?<\/desc>/gi, '');

// Process <style> inside SVG so that it is properly wrapped as JSX string
svgInner = svgInner.replace(/<style\b[^>]*>([\s\S]*?)<\/style>/gi, (_, css) => {
  return `<style>{\`${css}\`}</style>`;
});

// Helper to convert HTML/SVG attributes to JSX camelCase
function htmlToJsx(str) {
  return str
    .replace(/\bclass="/g, 'className="')
    .replace(/\btabindex="(\d+)"/g, 'tabIndex={$1}')
    .replace(/\btabindex="/g, 'tabIndex="')
    .replace(/\bstop-color="/g, 'stopColor="')
    .replace(/\bstop-opacity="/g, 'stopOpacity="')
    .replace(/\bstroke-width="/g, 'strokeWidth="')
    .replace(/\bstroke-linecap="/g, 'strokeLinecap="')
    .replace(/\bstroke-linejoin="/g, 'strokeLinejoin="')
    .replace(/\bstroke-dasharray="/g, 'strokeDasharray="')
    .replace(/\bletter-spacing="/g, 'letterSpacing="')
    .replace(/\bfont-size="/g, 'fontSize="')
    .replace(/\bfont-weight="/g, 'fontWeight="')
    .replace(/\btext-anchor="/g, 'textAnchor="')
    .replace(/\bmarker-end="/g, 'markerEnd="')
    .replace(/\bmarker-start="/g, 'markerStart="')
    .replace(/\bmarker-mid="/g, 'markerMid="')
    .replace(/\bpatternunits="/gi, 'patternUnits="')
    .replace(/\brefx="/gi, 'refX="')
    .replace(/\brefy="/gi, 'refY="')
    .replace(/\bmarkerwidth="/gi, 'markerWidth="')
    .replace(/\bmarkerheight="/gi, 'markerHeight="')
    .replace(/\bclip-path="/g, 'clipPath="')
    .replace(/\bstyle="--step:(\d+)"/g, 'style={{ "--step": $1 } as React.CSSProperties}')
    .replace(/\bstyle="([^"]*)"/g, (m, styleContent) => {
      if (styleContent.includes('CSSProperties') || styleContent.startsWith('{`')) return m;
      return `style={${JSON.stringify(
        Object.fromEntries(
          styleContent
            .split(';')
            .filter(Boolean)
            .map((pair) => {
              const [k, v] = pair.split(':').map((s) => s.trim());
              return [k, v];
            }),
        ),
      )}}`;
    });
}

